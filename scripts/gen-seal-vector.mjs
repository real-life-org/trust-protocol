#!/usr/bin/env node
// Generates vectors/seal.json: the sealed envelope of Delivery Section 5
// over a seal-only sample document, from fixed inputs (recipient and
// ephemeral X25519 keys, nonce, document). JCS plaintext → X25519 →
// HKDF-SHA-256 ("rltp/v1/seal") → AES-256-GCM, and the document digest
// (sha2-256 multihash, `u`). The sample's type is a Type URI of the
// namespace (Delivery RLTP-DEL-3010) that names no registered type.
//
//   usage: node scripts/gen-seal-vector.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createPrivateKey, createPublicKey, diffieHellman, hkdfSync, createCipheriv, createHash } from 'node:crypto'
import { jcs } from '../conformance/lib.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const FILE = join(ROOT, 'vectors/seal.json')
const committed = readFileSync(FILE, 'utf8')
const v = JSON.parse(committed)
const b64u = (b) => Buffer.from(b).toString('base64url')
const xPriv = (raw) => createPrivateKey({ key: Buffer.concat([Buffer.from('302e020100300506032b656e04220420', 'hex'), Buffer.from(raw, 'base64url')]), format: 'der', type: 'pkcs8' })
const xPubRaw = (priv) => { const s = createPublicKey(priv).export({ format: 'der', type: 'spki' }); return s.subarray(s.length - 32) }

const inputs = { ...v.inputs, document: { ...v.inputs.document, type: 'https://real-life.org/trust-tasks/spec/seal-vector-sample/0.1' } }
const recipient = xPriv(inputs.recipientPrivateKeyRaw), ephemeral = xPriv(inputs.ephemeralPrivateKeyRaw)
if (b64u(xPubRaw(recipient)) !== inputs.recipientPublicKeyRaw) throw new Error('recipientPublicKeyRaw is not the recipient key')
const plaintext = Buffer.from(jcs(inputs.document), 'utf8')
const shared = diffieHellman({ privateKey: ephemeral, publicKey: createPublicKey(recipient) })
if (shared.every((x) => x === 0)) throw new Error('all-zero shared secret')
const key = Buffer.from(hkdfSync('sha256', shared, Buffer.alloc(0), 'rltp/v1/seal', 32))
const c = createCipheriv('aes-256-gcm', key, Buffer.from(inputs.nonce, 'base64url'))
const ciphertext = Buffer.concat([c.update(plaintext), c.final(), c.getAuthTag()])

const out = {
  description: 'RLTP Delivery Contract section 5 seal vector. Digests are multibase(multihash) per CID 1.0. SEAL-ONLY SAMPLE: the plaintext document uses the reserved sample type and exercises the construction of section 5, not the document profile; it MUST NOT be processed as a delivery document. Deterministic inputs; implementations MUST reproduce ciphertext and documentDigest byte-for-byte. Generated by scripts/gen-seal-vector.mjs.',
  inputs,
  intermediate: { plaintextJcs: plaintext.toString('utf8'), sharedSecret: b64u(shared), hkdfInfo: 'rltp/v1/seal', aesKey: b64u(key) },
  output: {
    sealedEnvelope: { rkid: inputs.rkid, epk: b64u(xPubRaw(ephemeral)), nonce: inputs.nonce, ciphertext: b64u(ciphertext) },
    documentDigest: 'u' + b64u(Buffer.concat([Buffer.from([0x12, 0x20]), createHash('sha256').update(plaintext).digest()])),
  },
}
const rendered = JSON.stringify(out, null, 2) + '\n'
if (CHECK) {
  if (rendered !== committed) { console.error('vectors/seal.json: DIFFERS from its generation'); process.exit(1) }
  console.log('vectors/seal.json reproduces byte for byte')
} else {
  writeFileSync(FILE, rendered)
  console.log('vectors/seal.json written')
}

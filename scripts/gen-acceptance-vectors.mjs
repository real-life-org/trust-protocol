#!/usr/bin/env node
// Generates vectors/acceptance-anchoring.json — the executable vector
// family for the registration-generation machinery of Access §7.3 and
// its Replication consumers (§4.1, §6, §11):
//
//   · registrationCoreDigest identity (JCS minus sig minus authorization)
//   · quorum authorization over the complete unsigned registration
//     (domain separation = the artifact's own `v` constant inside the
//     signed JCS bytes, the keyRotation pattern)
//   · the two-way acceptance anchor: standing iff the root's core lies
//     on the previousRegistration chain into the session-attested
//     generation; everything else is invalid-bundle
//   · the CAS acceptance commit: expected-old re-check inside the
//     commit; two pre-validated candidates yield one acceptance
//   · registration equivocation: one generation, two core digests
//
// Deterministic: every key seed is sha256 of a fixed label. Re-running
// this script reproduces the vector file byte-for-byte.
//
//   usage: node scripts/gen-acceptance-vectors.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import crypto from 'node:crypto'
import { jcs, digestU, didOf, privEd, b58 } from '../conformance/lib.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const seed = (label) => crypto.createHash('sha256').update(`rltp/vector/acceptance/${label}`).digest()
const sign = (s, bytes) => 'z' + b58(crypto.sign(null, bytes, privEd(s)))

const S = {
  identity: seed('service-identity'),      // seq-0 derived service identity (signs every registration)
  quorumA: seed('quorum-member-a'),
  quorumB: seed('quorum-member-b'),
  k1: seed('attestation-key-gen1'),
  k2: seed('attestation-key-gen2'),
  k2x: seed('attestation-key-gen2-twin'),
  k3: seed('attestation-key-gen3'),
  k3n: seed('attestation-key-gen3-never-accepted'),
}
const did = Object.fromEntries(Object.entries(S).map(([k, s]) => [k, didOf(s)]))
const attKey = (k) => did[k].slice('did:key:'.length)

const genesisDigest = digestU({ vector: 'rltp/acceptance-anchoring', genesis: true })
const viewRootDigest = (n) => digestU({ vector: 'sole-tip-view-signature-input', seq: n })

const base = {
  v: 'rltp-access-registration/0.27',
  type: 'service-registration',
  group: did.identity,
  genesisDigest,
  identity: did.identity,
  service: 'https://relay.example/rltp',
  m: 1,
  class: 'view',
  stalenessBound: 'P7D',
  terminalRetention: 'P30D',
  divergenceQuota: 64,
}

const coreOf = (reg) => {
  const { sig, authorization, ...core } = reg
  return digestU(core)
}
const makeReg = ({ generation, attestation, prevCore, root, quorum, tweak }) => {
  let reg = {
    ...base,
    ...tweak,
    attestationKey: attKey(attestation),
    registrationGeneration: generation,
    previousRegistration: prevCore ?? null,
    authorizationRoot: root ?? null,
  }
  if (quorum) {
    const { sig, authorization, ...unsigned } = reg
    const bytes = Buffer.from(jcs(unsigned), 'utf8')
    reg.authorization = quorum
      .map((q) => ({ signer: did[q], sig: sign(S[q], bytes) }))
      .sort((a, b) => (a.signer < b.signer ? -1 : 1))
  }
  const { sig, ...toSign } = reg
  reg.sig = sign(S.identity, Buffer.from(jcs(toSign), 'utf8'))
  return reg
}

const gen1 = makeReg({ generation: 1, attestation: 'k1' })
const core1 = coreOf(gen1)
const gen2 = makeReg({ generation: 2, attestation: 'k2', prevCore: core1, root: viewRootDigest(12), quorum: ['quorumA', 'quorumB'] })
const core2 = coreOf(gen2)
const gen3 = makeReg({ generation: 3, attestation: 'k3', prevCore: core2, root: viewRootDigest(31), quorum: ['quorumA', 'quorumB'] })
const core3 = coreOf(gen3)
// equivocation twin: same generation 2, same predecessor, different core
const gen2twin = makeReg({ generation: 2, attestation: 'k2x', prevCore: core1, root: viewRootDigest(12), quorum: ['quorumA', 'quorumB'], tweak: { stalenessBound: 'P9D' } })
const core2twin = coreOf(gen2twin)
// validly authorized but never on the chain into the anchor
const gen3never = makeReg({ generation: 3, attestation: 'k3n', prevCore: core2, root: viewRootDigest(30), quorum: ['quorumA', 'quorumB'] })
const core3never = coreOf(gen3never)
// self-signed "acceptance": the candidate's own attestation key vouches
// for itself — void by construction, shown as an ignored extra artifact
const selfAcceptance = (() => {
  const body = { v: 'vector-self-acceptance', accepted: core3never }
  return { ...body, sig: sign(S.k3n, Buffer.from(jcs(body), 'utf8')) }
})()

const vector = {
  source:
    'Access §7.3 (registration generations, quorum authorization, the ' +
    'two-way acceptance anchor, the CAS acceptance commit, registration ' +
    'equivocation) · Replication §4.1/§6/§11. Generated by ' +
    'scripts/gen-acceptance-vectors.mjs (deterministic seeds). Signing ' +
    'profile: Encounter 2.3 (Ed25519 raw over JCS, base58btc z-form). ' +
    'Quorum domain separation is the v constant inside the signed bytes.',
  seeds: Object.fromEntries(Object.entries(S).map(([k, s]) => [k, s.toString('hex')])),
  parties: did,
  registrations: { gen1, gen2, gen3, gen2twin, gen3never },
  selfAcceptance,
  intermediate: {
    coreDigests: { gen1: core1, gen2: core2, gen3: core3, gen2twin: core2twin, gen3never: core3never },
  },
  anchorCases: [
    { name: 'ancestor gen1 through chain into session-attested gen3', root: 'gen1', sessionAttested: 'gen3', expect: 'standing' },
    { name: 'ancestor gen2 through chain into session-attested gen3', root: 'gen2', sessionAttested: 'gen3', expect: 'standing' },
    { name: 'session-attested generation itself', root: 'gen3', sessionAttested: 'gen3', expect: 'standing' },
    { name: 'no session anchor: every bundle is invalid', root: 'gen3', sessionAttested: null, expect: 'invalid-bundle' },
    { name: 'newest generation is provable only by the live session (freeze honesty)', root: 'gen3', sessionAttested: 'gen2', expect: 'invalid-bundle' },
    { name: 'equivocation twin is on no chain into the anchor', root: 'gen2twin', sessionAttested: 'gen3', expect: 'invalid-bundle', equivocationWith: 'gen2' },
    { name: 'validly authorized but never accepted: no successor binding, no attestation', root: 'gen3never', sessionAttested: 'gen3', expect: 'invalid-bundle' },
    { name: 'self-signed acceptance is void: the extra artifact changes nothing', root: 'gen3never', sessionAttested: 'gen3', extraArtifact: 'selfAcceptance', expect: 'invalid-bundle' },
  ],
  casCases: [
    { name: 'two pre-validated candidates, first commits', state: 'gen1', schedule: [['precheck', 'gen2'], ['precheck', 'gen2twin'], ['commit', 'gen2'], ['commit', 'gen2twin']], expect: { outcomes: ['ok', 'ok', 'accepted', 'refused-expected-old'], finalState: 'gen2' } },
    { name: 'two pre-validated candidates, twin commits first (symmetric)', state: 'gen1', schedule: [['precheck', 'gen2twin'], ['precheck', 'gen2'], ['commit', 'gen2twin'], ['commit', 'gen2']], expect: { outcomes: ['ok', 'ok', 'accepted', 'refused-expected-old'], finalState: 'gen2twin' } },
    { name: 'crash before the commit advances nothing', state: 'gen1', schedule: [['precheck', 'gen2'], ['crash'], ['recover']], expect: { outcomes: ['ok', 'crashed', 'recovered'], finalState: 'gen1' } },
    { name: 'crash after the commit reproduces the accepted state', state: 'gen1', schedule: [['commit', 'gen2'], ['crash'], ['recover']], expect: { outcomes: ['accepted', 'crashed', 'recovered'], finalState: 'gen2' } },
    { name: 'generations never decrease: a gen-2 candidate against a gen-2 state is refused', state: 'gen2', schedule: [['commit', 'gen2twin']], expect: { outcomes: ['refused-expected-old'], finalState: 'gen2' } },
    { name: 'a gen-3 candidate expecting gen2 commits against gen2', state: 'gen2', schedule: [['commit', 'gen3']], expect: { outcomes: ['accepted'], finalState: 'gen3' } },
  ],
  negative: [
    { name: 'root substitution: tampered authorizationRoot breaks every quorum signature', registration: 'gen2', set: { authorizationRoot: viewRootDigest(11) }, mustFail: 'quorum-signature' },
    { name: 'tampered previousRegistration breaks the identity signature', registration: 'gen2', set: { previousRegistration: core2 }, mustFail: 'identity-signature' },
    { name: 'a g+1 registration without authorization is schema-invalid', registration: 'gen2', del: ['authorization'], mustFail: 'schema' },
    { name: 'generation 1 with an authorization block is schema-invalid', registration: 'gen1', set: { authorization: [] }, mustFail: 'schema' },
  ],
}

const text = JSON.stringify(vector, null, 1) + '\n'
const path = join(ROOT, 'vectors/acceptance-anchoring.json')
if (CHECK) {
  if (readFileSync(path, 'utf8') !== text) { console.error('vectors/acceptance-anchoring.json is not what the generator produces'); process.exit(1) }
  console.log('vectors/acceptance-anchoring.json reproduces byte for byte')
} else {
  writeFileSync(path, text)
  console.log('vectors/acceptance-anchoring.json written:',
    Object.keys(vector.registrations).length, 'registrations,',
    vector.anchorCases.length, 'anchor cases,',
    vector.casCases.length, 'CAS cases,',
    vector.negative.length, 'negatives')
}

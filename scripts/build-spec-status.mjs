#!/usr/bin/env node
// Writes what spec/status.json says about each specification to the places
// a reader meets it first:
//
//   · a status block at the top of every spec/*.md, between the markers
//     <!-- spec-status:begin … --> and <!-- spec-status:end -->; the rest of
//     the file stays byte for byte as it is;
//   · the status section of README.md, between the same markers;
//   · the document table of the site page
//     apps/site/src/content/docs/reference/specifications.md, between them;
//   · every statement about what the library builds today on README.md, the
//     site's components and pages and spec/direction/*.md, between
//     <!-- now:<id>[:short|:long] --> and <!-- /now:<id> --> (in MDX
//     {/* now:<id> */} and {/* /now:<id> */}), from the entry <id> of the
//     `statements` of status.json.
//
// It checks status.json first: every spec/*.md has exactly one entry and
// every entry a file; the frozen text of each file (everything below the
// block) has the SHA-256 digest its entry names in `textDigest`, so an edit
// of a frozen text fails; the version (and date, where the header has one)
// is the one in the file's header; every status is defined; every section
// a part names is a heading of the file; every reference and target is
// non-empty and every path a part names (in `ref`, `target`, `source`)
// exists; every deviation a part names is a row of lib/DEVIATIONS.md, and
// every row is named at each document its reading names (Identity, Access,
// …); every part that is built, partly built or built differently names
// `evidence`, paths in the library, the vectors or the ceremony
// definitions that exist; every statement has a short form, at most a
// long one besides, and existing evidence, every statement is used at
// least once, every marker names a statement and form that exist, and
// every begin marker has exactly one end marker before the next begin.
//
//   usage: node scripts/build-spec-status.mjs [--check]
//
// --check writes nothing and fails when a generated place differs.
// Exit 1 on any error, 2 on usage errors.
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { join, dirname, resolve, posix } from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const REPO = 'https://github.com/real-life-org/trust-protocol/blob/main'
export const BEGIN = '<!-- spec-status:begin (generated by scripts/build-spec-status.mjs from spec/status.json; do not edit) -->'
export const END = '<!-- spec-status:end -->'
const README = 'README.md'
const SITE = 'apps/site/src/content/docs/reference/specifications.md'
const DOCS = 'apps/site/src/content/docs'
export const BOX = {
  md: { begin: '<!-- spec-box:begin (generated by scripts/build-spec-status.mjs from spec/status.json; do not edit) -->', end: '<!-- spec-box:end -->' },
  mdx: { begin: '{/* spec-box:begin (generated by scripts/build-spec-status.mjs from spec/status.json; do not edit) */}', end: '{/* spec-box:end */}' },
}

const LABEL = {
  built: 'built',
  'partly-built': 'partly built',
  'built-differently': 'built differently',
  'not-built': 'not built',
  superseded: 'superseded',
  parked: 'parked',
  'direction-changed': 'direction changed',
  'not-verified': 'not verified',
}

const PRECEDENCE = 'Where a specification text and the library disagree, the library with its vectors and flows holds until the text is brought up to date.'

// ── the block in a specification ────────────────────────────────────────

// A specification's text without its generated block, and the block.
const count = (text, marker) => text.split(marker).length - 1

// Exactly one begin and one end marker, in that order, or none.
export function markerProblem(text) {
  const b = count(text, BEGIN), e = count(text, END)
  if (b === 0 && e === 0) return null
  if (b !== 1 || e !== 1) return `${b} begin and ${e} end markers, not one of each`
  if (text.indexOf(END) < text.indexOf(BEGIN)) return 'the end marker stands before the begin marker'
  return null
}

export function splitSpec(text) {
  const problem = markerProblem(text)
  if (problem) throw new Error(`status block: ${problem}`)
  if (!text.startsWith(BEGIN)) {
    if (count(text, BEGIN)) throw new Error('status block: not at the top of the file')
    return { block: null, rest: text }
  }
  const end = text.indexOf(END)
  let rest = text.slice(end + END.length)
  if (rest.startsWith('\n\n')) rest = rest.slice(2)
  else if (rest.startsWith('\n')) rest = rest.slice(1)
  return { block: text.slice(0, end + END.length), rest }
}

export const joinSpec = (block, rest) => `${block}\n\n${rest}`

// Replace what stands between the markers in a page; null when it has none.
export function replaceBetween(text, body) {
  if (!count(text, BEGIN) || markerProblem(text)) return null
  const b = text.indexOf(BEGIN)
  const e = text.indexOf(END)
  return `${text.slice(0, b)}${BEGIN}\n${body}\n${text.slice(e)}`
}

// ── rendering ───────────────────────────────────────────────────────────

const deviation = (id) => /^D\d+$/.test(id)
const sectionsOf = (p) => (p.sections ?? []).map((s) => `§${s}`).join(', ')
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

// A path given relative to spec/, or to the repository root when it starts
// with a top-level directory other than spec/.
const OUTSIDE = /^(lib|interop|binding|vectors|schemas|conformance)\//
const repoPathOf = (path) => OUTSIDE.test(path) ? path : `spec/${path}`

// A link written from `from` ('spec', 'root' or 'site'). From a spec, a
// path outside spec/ is a repository link: the site publishes spec/ as raw
// files beside the pages, but not lib/.
function link(path, text, from) {
  const repoPath = repoPathOf(path)
  const href = from === 'site' ? `${REPO}/${repoPath}` : from === 'root' ? repoPath : (repoPath.startsWith('spec/') ? repoPath.slice(5) : `${REPO}/${repoPath}`)
  return `[${text ?? path}](${href})`
}

function refs(part, from) {
  const out = []
  const list = refsOf(part)
  for (const r of list) {
    if (deviation(r)) out.push(link('lib/DEVIATIONS.md', r, from))
    else if (isPath(r) && !/\s/.test(r)) out.push(link(r, r, from))
    else out.push(r)
  }
  if (part.target) out.push(`by ${link(part.target, part.target.split('/').pop(), from)}`)
  return out.join(', ')
}

export const BUILT_MEANS = '*Built* means the library implements the part; the text has not been reconciled with the library rule by rule, so single rules may differ.'
const reconciled = (r) => r === 'not reconciled'
  ? '**Not reconciled** with the library rule by rule, so in the table below *built* means the library implements the part and single rules may differ.'
  : `**Last reconciled against the library:** ${r}. ${BUILT_MEANS}`

export function renderSpecBlock(doc) {
  const lines = [
    BEGIN,
    `> **Status, generated from [\`status.json\`](status.json).** This text is frozen at version ${doc.version} (${doc.date}) and is not edited. ${PRECEDENCE} The library is [\`lib/\`](${REPO}/lib/README.md). Earlier versions under [\`archive/\`](archive/) are history, not the current state.`,
    '>',
    `> **State:** ${doc.state}. ${reconciled(doc.lastReconciled)}${doc.direction ? ` **Direction:** ${link(doc.direction, doc.direction, 'spec')} (not built, not normative).` : ''}`,
    '>',
    '> | Part | Status | Note |',
    '> |---|---|---|',
    ...doc.parts.map((p) => {
      const what = [sectionsOf(p), p.title].filter(Boolean).join(' ')
      const status = [LABEL[p.status], refs(p, 'spec')].filter(Boolean).join(': ')
      return `> | ${cell(what)} | ${cell(status)} | ${cell(p.note)} |`
    }),
  ]
  if (doc.note) lines.push('>', `> ${doc.note}`)
  lines.push(END)
  return lines.join('\n')
}

export function renderReadme(status) {
  return [
    `The texts under [\`spec/\`](spec/) are frozen at the version named below and are not edited, apart from a generated status block at their top. They are brought up to date one flow at a time. What holds, part by part, is in [\`spec/status.json\`](spec/status.json). ${BUILT_MEANS.replace('the text has', 'the texts have')} ${PRECEDENCE}`,
    '',
    '| Document | Version | State | Last reconciled |',
    '|---|---|---|---|',
    ...status.documents.map((d) => `| ${link(d.file, d.title, 'root')} | ${d.version} | ${cell(d.state)}${d.direction ? ` (${link(d.direction, 'direction', 'root')})` : ''} | ${d.lastReconciled} |`),
  ].join('\n')
}

export function renderSite(status) {
  return [
    `What holds, part by part, is in [\`spec/status.json\`](${REPO}/spec/status.json) and at the top of each document. ${PRECEDENCE}`,
    '',
    '| Document | Role | Version | State |',
    '|---|---|---|---|',
    ...status.documents.map((d) => `| ${link(d.file, d.title, 'site')} | ${cell(d.role)} | ${d.version} | ${cell(d.state)}${d.direction ? ` (${link(d.direction, 'direction', 'site')})` : ''} |`),
  ].join('\n')
}

// ── checks of status.json ───────────────────────────────────────────────

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

export const digestOf = (text) => `sha256:${createHash('sha256').update(text, 'utf8').digest('hex')}`

// The specification a deviation's reading names, by the name it uses.
const NAMES = { Identity: 'identity-layer.md', Encounter: 'encounter-layer.md', Trust: 'trust-layer.md', Access: 'access-layer.md', Membership: 'membership-tasks.md', Message: 'message-tasks.md', Delivery: 'delivery-contract.md', Replication: 'replication-contract.md', VTI: 'adapter-vti-mediator.md' }

export function deviationRows(text) {
  const rows = {}
  for (const line of text.split('\n')) {
    const m = line.match(/^\| (D\d+) \|/)
    if (!m) continue
    const reading = line.split('|').slice(5).join('|')
    rows[m[1]] = [...new Set([...reading.matchAll(new RegExp(`\\b(${Object.keys(NAMES).join('|')})\\b`, 'g'))].map((n) => NAMES[n[1]]))]
  }
  return rows
}

const refsOf = (p) => p.ref === undefined ? [] : Array.isArray(p.ref) ? p.ref : [p.ref]
const pathIn = (s) => (typeof s === 'string' ? s.trim().split(/\s+/)[0] : '')
// One reading of a file path for `ref`, `target` and `source`: a first word
// with a slash or a file extension.
export const isPath = (token) => /\//.test(token) || /\.(md|json|ts|mjs|js|txt)$/.test(token)
const fullPath = (root, path) => join(root, repoPathOf(path))

// A path names a regular file of the repository, written in its normal
// form (no `..`, no `.`, no trailing slash) and, when `within` is given,
// inside that directory of the repository.
export function fileProblem(root, path, within) {
  if (typeof path !== 'string' || !path) return 'is empty'
  const normal = posix.normalize(path)
  if (normal !== path || path.endsWith('/') || path.startsWith('/') || normal.startsWith('..')) return 'is not a path in normal form'
  if (within && !normal.startsWith(within)) return `is not under ${within}`
  const full = join(root, normal)
  if (!existsSync(full)) return 'does not exist'
  if (!statSync(full).isFile()) return 'is not a file'
  return null
}

export function checkStatus(root, status) {
  const errors = []
  const files = readdirSync(join(root, 'spec')).filter((f) => f.endsWith('.md')).sort()
  const entries = status.documents.map((d) => d.file)
  for (const f of files) if (!entries.includes(f)) errors.push(`spec/${f} has no entry in spec/status.json`)
  for (const f of entries) if (!files.includes(f)) errors.push(`spec/status.json names ${f}, which is not in spec/`)
  for (const f of new Set(entries)) if (entries.filter((e) => e === f).length > 1) errors.push(`spec/status.json names ${f} more than once`)
  const devText = existsSync(join(root, 'lib/DEVIATIONS.md')) ? readFileSync(join(root, 'lib/DEVIATIONS.md'), 'utf8') : ''
  const rows = deviationRows(devText)
  const namedAt = {}
  for (const d of status.documents) {
    const where = `spec/status.json ${d.file}`
    if (!files.includes(d.file)) continue
    for (const k of ['title', 'role', 'version', 'date', 'state', 'lastReconciled', 'textDigest']) if (!d[k]) errors.push(`${where}: no ${k}`)
    let text
    try { text = splitSpec(readFileSync(join(root, 'spec', d.file), 'utf8')).rest } catch (err) { errors.push(`spec/${d.file}: ${err.message}`); continue }
    const digest = digestOf(text)
    if (d.textDigest && d.textDigest !== digest) errors.push(`${where}: the frozen text has changed (textDigest ${d.textDigest}, the file below its status block is ${digest})`)
    const version = text.match(/^- \*\*Version:\*\*\s*(\S+)/m)?.[1]
    if (version !== d.version) errors.push(`${where}: version ${d.version}, header says ${version}`)
    const date = text.match(/^- \*\*Date:\*\*\s*(\S+)/m)?.[1]
    if (date && date !== d.date) errors.push(`${where}: date ${d.date}, header says ${date}`)
    if (d.direction !== undefined) { const why = fileProblem(root, `spec/${d.direction}`, 'spec/direction/'); if (why) errors.push(`${where}: direction ${d.direction} ${why}`) }
    if (!Array.isArray(d.parts) || !d.parts.length) errors.push(`${where}: no parts`)
    for (const p of d.parts ?? []) {
      const pw = `${where} "${p.title}"`
      if (!p.title) errors.push(`${where}: a part without a title`)
      if (typeof p.status !== 'string' || !Object.hasOwn(status.statuses ?? {}, p.status) || !Object.hasOwn(LABEL, p.status)) errors.push(`${pw}: unknown status ${p.status}`)
      if (p.status === 'partly-built' && !(typeof p.note === 'string' && p.note.trim())) errors.push(`${pw}: partly-built without a note saying which part`)
      if (['built', 'partly-built', 'built-differently'].includes(p.status)) errors.push(...evidenceProblems(root, p.evidence, pw))
      else if (p.evidence !== undefined) errors.push(...evidenceProblems(root, p.evidence, pw))
      const list = refsOf(p)
      if (p.ref !== undefined && (!list.length || list.some((r) => typeof r !== 'string' || !r.trim()))) errors.push(`${pw}: an empty ref`)
      if (p.target !== undefined && (typeof p.target !== 'string' || !p.target.trim())) errors.push(`${pw}: an empty target`)
      if (p.status === 'built-differently' && !list.length) errors.push(`${pw}: built-differently without ref`)
      if (p.status === 'direction-changed' && !list.some((r) => typeof r === 'string' && /\.md$/.test(pathIn(r)) && !fileProblem(root, `spec/${pathIn(r)}`, 'spec/direction/'))) errors.push(`${pw}: direction-changed without a ref to a direction note under spec/direction/`)
      if (p.status === 'superseded' && !p.target) errors.push(`${pw}: superseded without target`)
      for (const s of p.sections ?? []) {
        if (!new RegExp(`^#{2,6} ${esc(s)}\\.?(?:\\s|$)`, 'm').test(text)) errors.push(`${pw}: spec/${d.file} has no section ${s}`)
      }
      for (const r of list) {
        if (deviation(r)) {
          ;(namedAt[r] ??= new Set()).add(d.file)
          if (!(r in rows)) errors.push(`${pw}: ${r} is no row of lib/DEVIATIONS.md`)
        } else {
          const path = pathIn(r)
          if (isPath(path)) { const why = fileProblem(root, repoPathOf(path)); if (why) errors.push(`${pw}: ref ${path} ${why}`) }
        }
      }
      if (p.target) { const why = fileProblem(root, repoPathOf(p.target)); if (why) errors.push(`${pw}: target ${p.target} ${why}`) }
      for (const item of (p.source ?? '').split(';')) {
        const path = pathIn(item)
        if (isPath(path)) { const why = fileProblem(root, repoPathOf(path)); if (why) errors.push(`${pw}: source ${path} ${why}`) }
      }
    }
  }
  for (const [r, docs] of Object.entries(rows)) {
    if (!namedAt[r]) { errors.push(`lib/DEVIATIONS.md ${r} is named by no part in spec/status.json`); continue }
    for (const f of docs) if (entries.includes(f) && !namedAt[r].has(f)) errors.push(`lib/DEVIATIONS.md ${r} names ${f}, whose entry in spec/status.json does not name it`)
  }
  return errors
}

// ── statements about what the library builds today ──────────────────────

export const EVIDENCE = /^(lib\/(src|test)\/|vectors\/|interop\/ceremonies\/|binding\/|conformance\/|schemas\/)/
// A statement about the app is evidenced only by a file of the public app
// repository at a fixed commit.
export const APP_EVIDENCE = /^https:\/\/github\.com\/real-life-org\/web-of-trust\/blob\/[0-9a-f]{40}\/[^\s#]+(#L\d+(-L\d+)?)?$/
const FORMS = ['short', 'long']
const MARKS = {
  html: { begin: /<!-- now:([a-z0-9-]+)(?::([a-z]+))? -->/g, end: (id) => `<!-- /now:${id} -->`, stray: /<!-- \/now:([a-z0-9-]+) -->/g },
  mdx: { begin: /\{\/\* now:([a-z0-9-]+)(?::([a-z]+))? \*\/\}/g, end: (id) => `{/* /now:${id} */}`, stray: /\{\/\* \/now:([a-z0-9-]+) \*\/\}/g },
}

// The files that may carry statements: README.md, the site's components
// and pages, and the direction notes.
export function statementFiles(root) {
  const out = []
  const walk = (dir, re) => {
    if (!existsSync(join(root, dir))) return
    for (const e of readdirSync(join(root, dir), { withFileTypes: true })) {
      const p = `${dir}/${e.name}`
      if (e.isDirectory()) walk(p, re)
      else if (re.test(e.name)) out.push(p)
    }
  }
  if (existsSync(join(root, README))) out.push(README)
  walk('apps/site/src/components', /\.astro$/)
  walk('apps/site/src/content/docs', /\.mdx?$/)
  walk('spec/direction', /\.md$/)
  return out.sort()
}

// A statement as the file needs it: Markdown as written, HTML in an Astro
// component.
export function renderStatement(text, file) {
  if (!file.endsWith('.astro')) return text
  const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  return esc(text).replace(/`([^`]+)`/g, '<code>$1</code>').replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '<a href="$2">$1</a>')
}

// The statements a file uses, each with its form.
export function statementUses(text, file) {
  const mark = MARKS[file.endsWith('.mdx') ? 'mdx' : 'html']
  return [...text.matchAll(mark.begin)].map((m) => ({ id: m[1], form: m[2] ?? 'short' }))
}

// Fill every marked place of a file from the statements; errors for a
// marker that names no statement or form, a begin without its end, a
// begin inside another place, or an end without its begin.
export function fillStatements(text, statements, file) {
  const mark = MARKS[file.endsWith('.mdx') ? 'mdx' : 'html']
  const errors = []
  let out = ''
  let at = 0
  const begins = [...text.matchAll(mark.begin)]
  let pairs = 0
  for (let i = 0; i < begins.length; i++) {
    const m = begins[i]
    if (m.index < at) continue
    const id = m[1], form = m[2] ?? 'short'
    const open = m.index + m[0].length
    const endMark = mark.end(id)
    const end = text.indexOf(endMark, open)
    const next = begins[i + 1]?.index ?? Infinity
    if (end === -1 || end > next) { errors.push(`${file}: now:${id} has no end marker before the next statement`); continue }
    pairs++
    const st = statements[id]
    if (!st) errors.push(`${file}: now:${id} names no statement in spec/status.json`)
    else if (!FORMS.includes(form) || !st[form]) errors.push(`${file}: now:${id} names no form ${form}`)
    const old = text.slice(open, end)
    const block = old.startsWith('\n')
    // Markdown reads a line that begins with a comment as raw HTML: an inline place must not start a line
    if (!block && file.endsWith('.md') && (m.index === 0 || text[m.index - 1] === '\n')) errors.push(`${file}: now:${id} starts a line; write it after text on the line, or as a block on lines of its own`)
    const body = st?.[form] ? renderStatement(st[form], file) : old.trim()
    out += text.slice(at, open) + (block ? `\n${body}\n` : body)
    at = end
  }
  out += text.slice(at)
  const ends = [...text.matchAll(mark.stray)].length
  if (ends !== pairs) errors.push(`${file}: ${ends} end markers for ${pairs} statements`)
  // a comment that looks like a marker but is none (a capital, a space) is refused
  const loose = file.endsWith('.mdx') ? /\{\/\*\s*\/?\s*now\s*:[^}]*\*\/\}/gi : /<!--\s*\/?\s*now\s*:[\s\S]*?-->/gi
  // the syntax the parser consumes: a begin may name a form, an end never does
  const strict = file.endsWith('.mdx') ? /^\{\/\* (now:[a-z0-9-]+(:[a-z]+)?|\/now:[a-z0-9-]+) \*\/\}$/ : /^<!-- (now:[a-z0-9-]+(:[a-z]+)?|\/now:[a-z0-9-]+) -->$/
  for (const m of text.matchAll(loose)) if (!strict.test(m[0])) errors.push(`${file}: ${m[0]} is no statement marker`)
  return { text: out, errors }
}

// A file's text with every generated place emptied: what a person wrote.
export function outsideGenerated(text, file) {
  const mdx = file.endsWith('.mdx')
  const now = mdx ? /(\{\/\* now:([a-z0-9-]+)(?::[a-z]+)? \*\/\})[\s\S]*?(\{\/\* \/now:\2 \*\/\})/g : /(<!-- now:([a-z0-9-]+)(?::[a-z]+)? -->)[\s\S]*?(<!-- \/now:\2 -->)/g
  let out = text.replace(now, '$1$3')
  const box = BOX[mdx ? 'mdx' : 'md']
  const bb = out.indexOf(box.begin), be = out.indexOf(box.end)
  if (bb !== -1 && be > bb) out = out.slice(0, bb + box.begin.length) + out.slice(be)
  const b = out.indexOf(BEGIN), e = out.indexOf(END)
  if (b !== -1 && e > b) out = out.slice(0, b + BEGIN.length) + out.slice(e)
  return out
}

// The statements whose wording stands in a file outside its generated
// places: a place whose markers were removed and whose text stayed.
export function unmarkedStatements(text, file, statements) {
  const outside = outsideGenerated(text, file)
  const out = []
  for (const [id, st] of Object.entries(statements ?? {})) {
    for (const form of FORMS) if (typeof st?.[form] === 'string' && st[form].length > 40 && outside.includes(renderStatement(st[form], file))) out.push(id)
  }
  return [...new Set(out)]
}

export function checkStatements(root, status, files) {
  const errors = []
  const statements = status.statements ?? {}
  const used = new Set()
  for (const file of files) {
    const text = readFileSync(join(root, file), 'utf8')
    for (const u of statementUses(text, file)) used.add(u.id)
    errors.push(...fillStatements(text, statements, file).errors)
    errors.push(...unmarkedStatements(text, file, statements).map((id) => `${file}: the statement ${id} stands without its markers`))
  }
  for (const [id, st] of Object.entries(statements)) {
    const where = `spec/status.json statement ${id}`
    if (!/^[a-z0-9-]+$/.test(id)) errors.push(`${where}: an id is lower case letters, digits and hyphens`)
    if (typeof st.short !== 'string' || !st.short.trim()) errors.push(`${where}: no short form`)
    if (st.long !== undefined && (typeof st.long !== 'string' || !st.long.trim())) errors.push(`${where}: an empty long form`)
    for (const k of Object.keys(st)) if (![...FORMS, 'evidence'].includes(k)) errors.push(`${where}: unknown field ${k}`)
    errors.push(...evidenceProblems(root, st.evidence, where))
    if (!used.has(id)) errors.push(`${where}: used on no page`)
  }
  return errors
}

function evidenceProblems(root, evidence, where) {
  if (!Array.isArray(evidence) || !evidence.length) return [`${where}: no evidence`]
  const errors = []
  for (const e of evidence) {
    if (typeof e === 'string' && APP_EVIDENCE.test(e)) continue
    const prefix = typeof e === 'string' && e.match(EVIDENCE)?.[0]
    if (!prefix) { errors.push(`${where}: evidence ${e} is no path in the library, the vectors or the ceremony definitions`); continue }
    const why = fileProblem(root, e, prefix)
    if (why) errors.push(`${where}: evidence ${e} ${why}`)
  }
  return errors
}

// ── the box on the explaining pages ─────────────────────────────────────

// The pages under understand/ and reference/ that rest on specifications
// (a non-empty `specs:`), with those specifications; the list of the
// specifications itself carries the generated table instead.
export function boxPages(root) {
  const out = []
  for (const dir of ['understand', 'reference']) {
    const full = join(root, DOCS, dir)
    if (!existsSync(full)) continue
    for (const name of readdirSync(full).sort()) {
      if (!/\.mdx?$/.test(name)) continue
      const file = `${DOCS}/${dir}/${name}`
      if (file === SITE) continue
      const fm = readFileSync(join(root, file), 'utf8').match(/^---\n([\s\S]*?)\n---/)?.[1] ?? ''
      const specs = fm.match(/^specs:\s*\[(.*)\]\s*$/m)?.[1].split(',').map((x) => x.trim()).filter(Boolean) ?? []
      if (specs.length) out.push({ file, specs })
    }
  }
  return out
}

const lowerFirst = (t) => t.charAt(0).toLowerCase() + t.slice(1)

export function renderBox(specs, status, file) {
  const box = BOX[file.endsWith('.mdx') ? 'mdx' : 'md']
  const docs = specs.map((name) => status.documents.find((d) => d.file === `${name}.md`))
  const list = docs.map((d, i) => d ? `- [${d.title}](${REPO}/spec/${d.file}): ${lowerFirst(d.state)}` : `- ${specs[i]}: no entry in spec/status.json`)
  const lines = [box.begin, ':::note[Design and status]', 'This page describes the frozen specification texts. What the library builds of them:', '']
  if (docs.length > 4) lines.push('<details>', `<summary>The ${docs.length} specifications this page rests on</summary>`, '', ...list, '', '</details>')
  else lines.push(...list)
  lines.push('', 'Details, part by part: [Specifications](/reference/specifications/) and the status block at the top of each document.', ':::', box.end)
  return lines.join('\n')
}

// The page with its box: replaced between its markers, or set under the
// frontmatter (and an MDX page's imports) when it has none.
export function placeBox(text, box, file) {
  const m = BOX[file.endsWith('.mdx') ? 'mdx' : 'md']
  const count = (t) => text.split(t).length - 1
  const b = count(m.begin), e = count(m.end)
  if (b > 1 || e > 1 || b !== e) return { text, error: `${file}: ${b} box begin and ${e} box end markers, not one of each` }
  if (b === 1) {
    const i = text.indexOf(m.begin), j = text.indexOf(m.end)
    if (j < i) return { text, error: `${file}: the box end marker stands before its begin` }
    return { text: text.slice(0, i) + box + text.slice(j + m.end.length) }
  }
  const fm = text.match(/^---\n[\s\S]*?\n---\n/)
  if (!fm) return { text, error: `${file}: no frontmatter` }
  let at = fm[0].length
  const rest = text.slice(at)
  const imports = rest.match(/^(\n*(import [^\n]*\n)+)/)
  if (imports) at += imports[0].length
  const before = text.slice(0, at).replace(/\n*$/, '\n')
  return { text: `${before}\n${box}\n\n${text.slice(at).replace(/^\n+/, '')}` }
}

// ── generation: one result per file through every step ─────────────────

// Every generated place of the repository from status.json: the status
// block of each specification, the status section of README.md and the
// site's document table, then the statements in every file that carries
// them. Each file has one current text that every step reads and writes,
// so a later step never starts again from the file as it was. Returns the
// files with their text before and after, and the errors.
export function generate(root, status) {
  const files = statementFiles(root)
  const errors = [...checkStatus(root, status), ...checkStatements(root, status, files)]
  const current = new Map()
  const before = new Map()
  const text = (file) => {
    if (!current.has(file)) { const t = readFileSync(join(root, file), 'utf8'); before.set(file, t); current.set(file, t) }
    return current.get(file)
  }
  if (errors.length) return { errors, outputs: [] }
  for (const d of status.documents) {
    const file = `spec/${d.file}`
    current.set(file, joinSpec(renderSpecBlock(d), splitSpec(text(file)).rest))
  }
  for (const [file, body] of [[README, renderReadme(status)], [SITE, renderSite(status)]]) {
    if (!existsSync(join(root, file))) { errors.push(`${file}: missing`); continue }
    const next = replaceBetween(text(file), body)
    if (next === null) errors.push(`${file}: not exactly one ${BEGIN} … ${END} pair`)
    else current.set(file, next)
  }
  for (const { file, specs } of boxPages(root)) {
    const r = placeBox(text(file), renderBox(specs, status, file), file)
    if (r.error) errors.push(r.error)
    else current.set(file, r.text)
  }
  for (const file of files) current.set(file, fillStatements(text(file), status.statements ?? {}, file).text)
  return { errors, outputs: [...current].map(([file, after]) => [file, before.get(file), after]) }
}

// ── command line ────────────────────────────────────────────────────────

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const args = process.argv.slice(2)
  if (args.some((a) => a !== '--check')) {
    console.error('usage: node scripts/build-spec-status.mjs [--check]')
    process.exit(2)
  }
  const check = args.includes('--check')
  const status = JSON.parse(readFileSync(join(ROOT, 'spec/status.json'), 'utf8'))
  const { errors, outputs } = generate(ROOT, status)
  const stale = []
  if (!errors.length) {
    for (const [file, before, after] of outputs) {
      if (before === after) continue
      if (check) stale.push(file)
      else writeFileSync(join(ROOT, file), after)
    }
  }
  for (const e of errors) console.error(`  ERROR ${e}`)
  for (const f of stale) console.error(`  STALE ${f}: run node scripts/build-spec-status.mjs`)
  const failed = errors.length + stale.length
  console.log(failed ? `spec status: ${errors.length} error(s), ${stale.length} stale` : `spec status: ok, ${status.documents.length} documents, ${Object.keys(status.statements ?? {}).length} statements`)
  process.exit(failed ? 1 : 0)
}

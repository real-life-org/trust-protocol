#!/usr/bin/env node
// Generates vectors/proof-purpose.json: one document signed under
// eddsa-jcs-2022 with each proof purpose, and whether an RLTP verifier
// accepts it. The document is the body of the Trust Tasks TF baseline
// proof vector (vectors/tf-proof/eddsa-jcs-2022-baseline.json) and the
// key the TF's, Ed25519 from the seed [7; 32], so the `assertionMethod`
// case reproduces the TF baseline's proofValue byte for byte.
//
// A verifier accepts `assertionMethod` and `authentication` (Delivery
// DO-10; TT §4.7.3 asks a producer to sign for `authentication`); every
// other purpose, and an absent one, is refused although the signature
// holds. RLTP producers sign for `assertionMethod`.
//
//   usage: node scripts/gen-proof-purpose-vector.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import crypto from 'node:crypto'
import { jcs, sha, b58, privEd, didOf, diVerify } from '../conformance/lib.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const FILE = join(ROOT, 'vectors/proof-purpose.json')
const baseline = JSON.parse(readFileSync(join(ROOT, 'vectors/tf-proof/eddsa-jcs-2022-baseline.json'), 'utf8'))

const seed = Buffer.alloc(32, 7)
const did = didOf(seed)
const { proof: tfProof, ...document } = baseline
if (document.issuer !== did) throw new Error('the TF baseline is not signed by the key of seed [7; 32]')
const created = tfProof.created

const sign = (purpose) => {
  const cfg = { type: 'DataIntegrityProof', cryptosuite: 'eddsa-jcs-2022', created, verificationMethod: did + '#' + did.slice(8) }
  if (purpose !== null) cfg.proofPurpose = purpose
  const hashData = Buffer.concat([sha(Buffer.from(jcs(cfg), 'utf8')), sha(Buffer.from(jcs(document), 'utf8'))])
  const sig = crypto.sign(null, hashData, privEd(seed))
  return { ...document, proof: { ...cfg, proofValue: 'z' + b58(sig) } }
}

const CASES = [
  { name: 'assertionMethod', purpose: 'assertionMethod', expect: 'valid', rules: 'what RLTP producers sign with; the TF baseline byte for byte (TT §4.7.1)' },
  { name: 'authentication', purpose: 'authentication', expect: 'valid', rules: 'read beside assertionMethod (Delivery DO-10); the purpose TT §4.7.3 asks a producer to sign a Trust Task document with' },
  { name: 'capabilityInvocation', purpose: 'capabilityInvocation', expect: 'invalid', rules: 'a purpose RLTP does not read (Delivery DO-10); TT §4.7.3 lets a specification require a purpose and a consumer apply it as local policy' },
  { name: 'capabilityDelegation', purpose: 'capabilityDelegation', expect: 'invalid', rules: 'a purpose RLTP does not read (Delivery DO-10); TT §4.7.3 as above' },
  { name: 'keyAgreement', purpose: 'keyAgreement', expect: 'invalid', rules: 'TT §4.7.3 item 1: a key-agreement key never authorizes a signature' },
  { name: 'absent', purpose: null, expect: 'invalid', rules: 'TT §4.7.3 item 1: a proof without proofPurpose is rejected' },
]

const cases = CASES.map((c) => {
  const signed = sign(c.purpose)
  const signatureHolds = diVerify(signed, did).ok
  if (!signatureHolds) throw new Error(`${c.name}: the signature does not hold`)
  return { name: c.name, proofPurpose: c.purpose, expect: c.expect, rules: c.rules, signatureHolds, signed }
})
if (cases[0].signed.proof.proofValue !== tfProof.proofValue) throw new Error('assertionMethod: not the TF baseline proofValue')

const out = {
  description: 'Proof purposes under the RLTP securing profile (Encounter 2.3: eddsa-jcs-2022, did:key, the verification method the anchor\'s own key). One document — the body of the Trust Tasks TF baseline proof vector (vectors/tf-proof/eddsa-jcs-2022-baseline.json) — signed with the key of seed [7; 32] under each proof purpose; every signature holds. A verifier accepts the purposes assertionMethod and authentication and refuses every other purpose and an absent one (Delivery DO-10; TT §4.7.3). RLTP producers sign for assertionMethod; the schemas of the RLTP documents still pin it (DO-10), so for an RLTP document the schema check refuses authentication first. Generated by scripts/gen-proof-purpose-vector.mjs; re-derived by conformance/runner.mjs; lib/test/vectors.test.mjs runs every case through the library\'s diVerify.',
  signer: { seed: seed.toString('hex'), did },
  document,
  created,
  cases,
}
const rendered = JSON.stringify(out, null, 2) + '\n'
if (CHECK) {
  if (!existsSync(FILE) || rendered !== readFileSync(FILE, 'utf8')) { console.error('vectors/proof-purpose.json: DIFFERS from its generation'); process.exit(1) }
  console.log('vectors/proof-purpose.json reproduces byte for byte')
} else {
  writeFileSync(FILE, rendered)
  console.log('vectors/proof-purpose.json written')
}

#!/usr/bin/env node
// Generates vectors/shared-connect-binding.json: the enactment binding of
// the shared connection ceremony (shared-connect, a draft held jointly with
// Consensual), computed by the rule of Encounter RLTP-ENC-5330 under the
// ceremony's identifiers. The two challenges are canonical 16-byte values
// (VTI-LNK-033) chosen so that sorting them as strings and sorting their
// decoded bytes give different orders: the byte order is the slip a second
// implementation is most likely to make, and the vector names its result.
//
//   usage: node scripts/gen-shared-connect-binding-vector.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { digestU } from '../conformance/lib.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CHECK = process.argv.includes('--check')
const FILE = join(ROOT, 'vectors/shared-connect-binding.json')

const challengeOf = (bytes) => Buffer.from(bytes).toString('base64url')
const inviter = challengeOf(Array.from({ length: 16 }, (_, i) => i))
const responder = challengeOf(Array.from({ length: 16 }, (_, i) => 0xf0 + i))
for (const c of [inviter, responder]) if (!/^[A-Za-z0-9_-]{21}[AQgw]$/.test(c)) throw new Error(`${c}: not a canonical 16-byte challenge`)

const stringOrder = [inviter, responder].sort()
const byteOrder = [inviter, responder].sort((a, b) => Buffer.compare(Buffer.from(a, 'base64url'), Buffer.from(b, 'base64url')))
if (stringOrder[0] === byteOrder[0]) throw new Error('the challenges do not separate string order from byte order')

const CEREMONIES = [
  { ceremony: 'https://trusttasks.org/ceremony/shared-connect/0.2', note: 'the ceremony identifier (Trust Task framework §6.7), once the registry entry exists' },
  { ceremony: 'shared-connect@0.2', note: 'the working identifier of the draft, for test vectors only' },
]

const cases = CEREMONIES.map(({ ceremony, note }) => ({
  ceremony,
  note,
  descriptor: { ceremony, challenges: stringOrder },
  binding: digestU({ ceremony, challenges: stringOrder }),
  byteOrderSlip: digestU({ ceremony, challenges: byteOrder }),
}))

const out = {
  description: 'The enactment binding of the shared connection ceremony (shared-connect 0.2, a draft held jointly with Consensual): multibase u of the sha2-256 multihash over JCS({"ceremony": <identifier>, "challenges": [both challenges, ascending as strings]}), the construction of Encounter RLTP-ENC-5330 under this ceremony\'s identifiers. Both challenges are canonical 16-byte values, 22 characters of unpadded base64url with the four unused bits of the last one zero (VTI-LNK-033). They are chosen so that their string order and the order of their decoded bytes differ: `binding` is the rule, `byteOrderSlip` what an implementation that sorts decoded bytes computes, which a verifier must not accept. The roles do not enter: both parties compute the same binding. JCS leaves the slash of the identifier unescaped; a writer that escapes it as \\/ hashes other bytes. Generated by scripts/gen-shared-connect-binding-vector.mjs; re-derived by conformance/runner.mjs; lib/test/vectors.test.mjs recomputes it with the library\'s binding().',
  challenges: { inviter, responder },
  cases,
}
const rendered = JSON.stringify(out, null, 2) + '\n'
if (CHECK) {
  if (!existsSync(FILE) || rendered !== readFileSync(FILE, 'utf8')) { console.error('vectors/shared-connect-binding.json: DIFFERS from its generation'); process.exit(1) }
  console.log('vectors/shared-connect-binding.json reproduces byte for byte')
} else {
  writeFileSync(FILE, rendered)
  console.log('vectors/shared-connect-binding.json written')
}

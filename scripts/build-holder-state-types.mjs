#!/usr/bin/env node
// Generates lib/src/holder-state-v<n>.ts — the TypeScript projection of
// the NON-NORMATIVE lib/schemas/holder-state-v<n>.schema.json (the stored
// HolderState at codec n, for every codec the library reads: 3), the
// way build-wire-types.mjs generates wire.ts: properties, requiredness,
// literals, unions; every $defs entry becomes a named type with the suffix
// V<n>. What a type cannot carry (patterns, bounds, uniqueItems, order,
// if/then/else, not, dependentRequired) stays in the schema and in the
// codec's validator. lib/src/holder-state-check.ts holds the type of the
// current codec and the hand-written HolderState (state.ts) against each
// other at compile time; lib/test/holder-state-schema.test.mjs checks
// freshness.
//
//   usage: node scripts/build-holder-state-types.mjs           (write)
//          node scripts/build-holder-state-types.mjs --check   (drift)
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const CODECS = [3]
const SCHEMA = (n) => join(ROOT, `lib/schemas/holder-state-v${n}.schema.json`)
const OUT = (n) => join(ROOT, `lib/src/holder-state-v${n}.ts`)

const ident = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k))
const doc = (d, pad) => (d ? `${pad}/** ${d.replace(/\*\//g, '* /')} */\n` : '')

export function renderHolderStateTypes (schema, n = 1) {
  const render = (s, indent) => {
    const pad = '  '.repeat(indent), padIn = '  '.repeat(indent + 1)
    if (s === true || s === undefined) return 'Json'
    if (s === false) return 'never'
    if (typeof s.$ref === 'string') {
      const m = /^#\/\$defs\/(.+)$/.exec(s.$ref)
      if (!m || !schema.$defs[m[1]]) throw new Error('unresolvable $ref ' + s.$ref)
      return m[1] + 'V' + n
    }
    if (Array.isArray(s.enum)) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
    if ('const' in s) return JSON.stringify(s.const)
    if (Array.isArray(s.anyOf) || Array.isArray(s.oneOf)) return (s.anyOf ?? s.oneOf).map((b) => `(${render(b, indent)})`).join(' | ')
    switch (s.type) {
      case 'string': return 'string'
      case 'integer': case 'number': return 'number'
      case 'boolean': return 'boolean'
      case 'null': return 'null'
      case 'array': {
        const el = render(s.items, indent)
        return /[|&]/.test(el) ? `Array<${el}>` : `${el}[]`
      }
      case 'object': {
        const props = s.properties ?? {}
        const keys = Object.keys(props)
        if (!keys.length) {
          if (s.additionalProperties && typeof s.additionalProperties === 'object') return `Record<string, ${render(s.additionalProperties, indent)}>`
          return '{ [k: string]: Json }'
        }
        const req = new Set(s.required ?? [])
        const lines = keys.map((k) => `${doc(props[k].description, padIn)}${padIn}${ident(k)}${req.has(k) ? '' : '?'}: ${render(props[k], indent + 1)}`)
        if (s.additionalProperties === true) lines.push(`${padIn}[k: string]: Json`)
        return `{\n${lines.join('\n')}\n${pad}}`
      }
      default: return 'Json'
    }
  }
  const defs = Object.entries(schema.$defs).map(([name, s]) => `${doc(s.description, '')}export type ${name}V${n} = ${render(s, 0)}\n`)
  const { $defs, ...top } = schema
  return `// GENERATED by scripts/build-holder-state-types.mjs — DO NOT EDIT.
// Source: lib/schemas/holder-state-v${n}.schema.json (NON-NORMATIVE: the
// library's storage format at codec ${n}, not a protocol artifact). The
// structural projection only; the codec's validator (codec.ts) and the
// schema carry what a type cannot. holder-state-check.ts holds this type
// and state.ts's HolderState against each other.
import type { Json } from './core.js'

${doc(top.description, '')}export type HolderStateV${n} = ${render(top, 0)}

${defs.join('\n')}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const n of CODECS) {
    const out = renderHolderStateTypes(JSON.parse(readFileSync(SCHEMA(n), 'utf8')), n)
    if (process.argv.includes('--check')) {
      if (readFileSync(OUT(n), 'utf8') !== out) { console.error(`lib/src/holder-state-v${n}.ts drifted — re-run node scripts/build-holder-state-types.mjs`); process.exit(1) }
      console.log(`lib/src/holder-state-v${n}.ts is fresh`)
    } else {
      writeFileSync(OUT(n), out)
      console.log(`lib/src/holder-state-v${n}.ts generated`)
    }
  }
}
